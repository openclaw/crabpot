const digest = (bytes) => createHash("sha256").update(bytes).digest("hex");
const sha256 = /^[a-f0-9]{64}$/;
const hostFiles = [
  "dist/build-info.json", "scripts/e2e/kitchen-sink-rpc-walk.mts",
  "scripts/e2e/lib/kitchen-sink-resources.mts", "scripts/lib/gateway-bench-profile.ts",
  "scripts/lib/gateway-bench-profile-preload.ts",
];
const consumerFiles = [
  "crabpot.config.json", "scripts/run-resource-campaign.mjs", "scripts/run-resource-workload.mjs",
  "scripts/resource-workload-contract.mjs", "scripts/resource-coverage.mjs", "scripts/manifest-lib.mjs",
];
const entries = ["openclaw.mjs", "dist/index.mjs", "dist/index.js"];
const hashFile = (file) => digest(readFileSync(file));
const record = (value) => value !== null && typeof value === "object" && !Array.isArray(value);

function failureDiagnostic(error, stage) {
  const code = ["ENOENT", "EACCES", "EPERM", "ENOSPC", "EIO", "ERR_ASSERTION"].includes(error?.code) ? error.code : "UNKNOWN";
  const type = ["Error", "AssertionError", "TypeError", "RangeError", "SyntaxError", "ReferenceError"].includes(error?.name) ? error.name : "Error";
  // Never serialize arbitrary plugin exceptions, assertion actual/expected values,
  // causes or stacks. Validation messages are generated by these trusted owners.
  const firstLine = String(error?.message ?? "").split(/[\r\n]/u, 1)[0];
  const trusted = stage !== "run" && /^(?:resource coverage: |(?:host|crabpot) input changed: |Missing (?:host|crabpot|adapter) pin: |(?:Pinned|Receipt|Prepared|Built|Expected|Invalid|Declare|Pin the|Pins require|Artifact must) )/u.test(firstLine);
  const message = trusted ? firstLine
    .replace(/(?:api[_-]?key|token|password|secret|authorization)\s*[:=]\s*\S+/giu, "credential=[redacted]")
    .replace(/(['"])[\s\S]*?\1/gu, "[redacted]")
    .replace(/(?:[a-z]:[\\/]|\\\\|\/)[^\s,;)]*/giu, "[path]")
    .replace(/[\u0000-\u001f\u007f-\u009f\u061c\u200b-\u200f\u2028-\u202e\u2060-\u206f\ufeff]/gu, "?")
    .slice(0, 512) : stage === "run" ? "Workload runner threw without a terminal receipt" : "Diagnostic payload omitted; inspect prepared inputs or retained receipt";
  return { stage, type, code, message };
}

/** Verify prepared bytes only: no downloads, builds, installation or host imports. */
export function verifyPreparedInputs(pins, definitions, inventory, hostRoot, consumerRoot = repoRoot) {
  assert.equal(pins.schemaVersion, 1, "Expected resource campaign input pins v1");
  assert.equal(pins.hostCommit, inventory.source.commit, "Pinned host and inventory differ");
  assert.equal(process.versions.bun, undefined, "Pinned execution requires Node, not Bun");
  assert.deepEqual(pins.runtime, { node: process.version, platform: process.platform, arch: process.arch }, "Pinned runtime differs");
  for (const [scope, root, required] of [["host", hostRoot, hostFiles], ["crabpot", consumerRoot, consumerFiles]]) {
    const files = pins.files?.[scope];
    assert.ok(record(files), `Missing ${scope} file pins`);
    for (const file of required) assert.ok(Object.hasOwn(files, file), `Missing ${scope} pin: ${file}`);
    for (const [file, expected] of Object.entries(files)) {
      assert.ok(file && !path.posix.isAbsolute(file) && !path.win32.isAbsolute(file) && !file.split(/[\\/]/u).some((part) => part === ".." || part === "."), "Pins require relative file names");
      assert.match(expected, sha256, "Invalid file digest");
      assert.equal(hashFile(path.join(root, file)), expected, `${scope} input changed: ${file}`);
    }
  }
  assert.ok(entries.some((file) => Object.hasOwn(pins.files.host, file)), "Pin the built host entry");
  assert.equal(JSON.parse(readFileSync(path.join(hostRoot, "dist/build-info.json"), "utf8")).commit, pins.hostCommit, "Built host commit differs");
  for (const definition of definitions) {
    resourceWorkloadPlan(definition);
    const file = `scripts/resource-workloads/${definition.adapter}.mjs`;
    if (existsSync(path.join(consumerRoot, file))) assert.ok(Object.hasOwn(pins.files.crabpot, file), `Missing adapter pin: ${definition.id}`);
  }
  assert.ok(Array.isArray(pins.artifacts), "Declare prepared artifacts, including an empty list for bundled-only work");
  for (const artifact of pins.artifacts) {
    assert.ok(path.isAbsolute(artifact.path) && artifact.path.endsWith(".tgz"), "Artifact must be a local absolute archive path");
    assert.match(artifact.sha256, sha256);
    assert.equal(hashFile(artifact.path), artifact.sha256, "Prepared archive changed");
  }
}

function verifyReceiptPins(report, pins) {
  assert.equal(report.provenance.consumerSha256, pins.files.crabpot["scripts/run-resource-workload.mjs"], "Receipt consumer differs");
  assert.equal(report.provenance.contractSha256, pins.files.crabpot["scripts/resource-workload-contract.mjs"], "Receipt contract differs");
  for (const item of report.cases) for (const phase of item.phases) {
    if (phase.before?.runtime === undefined) continue; // Failed phases may lack a snapshot.
    // The preload records process.versions.node; campaign pins use process.version.
    // Normalize this one documented prefix difference, not arbitrary runtime aliases.
    assert.deepEqual(phase.before.runtime, { ...pins.runtime, node: pins.runtime.node.replace(/^v/u, "") }, "Receipt Gateway runtime differs from pins");
  }
  if (report.status !== "exercised") return;
  for (const file of hostFiles.filter((file) => file.startsWith("scripts/"))) {
    assert.equal(report.provenance.harnessSha256[file], pins.files.host[file], "Receipt harness differs");
  }
  for (const item of report.cases) {
    assert.ok(entries.some((file) => pins.files.host[file] === item.host.entrySha256), "Receipt host entry differs");
    for (const fixture of item.fixtures ?? []) {
      assert.ok(pins.artifacts.some((artifact) => artifact.sha256 === fixture.sha256), "Receipt contains an unpinned installed archive");
    }
  }
}

/** Sequential orchestration; the existing workload owner must join each Gateway and peer. */
export async function runResourceCampaign({
  manifest, inventory, pins, repetitions = 3, execute = false, hostRoot = process.cwd(),
}, {
  run = runResourceWorkload,
  verify = async () => {
    verifyPreparedInputs(pins, manifest.resourceWorkloads ?? [], inventory, hostRoot);
    assert.deepEqual(await readManifest(), manifest, "Prepared manifest changed after planning");
  },
  adapterAvailable = (definition) => existsSync(path.join(repoRoot, `scripts/resource-workloads/${definition.adapter}.mjs`)),
  save = () => {},
} = {}) {
  validatePluginInventory(inventory);
  assert.ok(Number.isSafeInteger(repetitions) && repetitions >= 1 && repetitions <= 10, "Repetitions must be 1..10");
  const definitions = manifest.resourceWorkloads ?? [];
  const ids = new Set();
  const plugins = new Set();
  for (const definition of definitions) {
    resourceWorkloadPlan(definition);
    for (const key of ["id", "pluginId", "adapter"]) assert.match(definition[key], /^[a-z0-9][a-z0-9-]*$/);
    assert.ok(!ids.has(definition.id) && !plugins.has(definition.pluginId), "Campaign requires one configured scenario per plugin");
    ids.add(definition.id); plugins.add(definition.pluginId);
  }
  const campaign = {
    schemaVersion: 1, kind: "plugin-resource-campaign", policy: "report-only", status: "blocked",
    inventory: { source: inventory.source, sha256: inventory.sha256, count: inventory.plugins.length },
    provenance: { inputsSha256: digest(JSON.stringify(pins)), files: pins.files, runtime: pins.runtime,
      artifacts: pins.artifacts?.map(({ path: file, sha256: hash }) => ({ archive: path.basename(file), sha256: hash })) },
    limitations: ["No performance budgets or leak verdicts", "External runner owns isolation and whole-sandbox termination", "Repetitions are separate observations, not independent plugin coverage", "Calibration is supplied and qualified separately"],
    unmatchedScenarios: definitions.filter(({ pluginId }) => !inventory.plugins.some(({ id }) => id === pluginId))
      .map(({ id, pluginId }) => ({ scenario: id, pluginId, status: "blocked", reason: "plugin-absent-from-inventory" })),
    repetitions: Array.from({ length: repetitions }, (_, index) => ({ repetition: index + 1,
      plugins: inventory.plugins.map(({ id, distribution }) => {
        const definition = definitions.find(({ pluginId }) => pluginId === id);
        return { id, distribution, ...(definition ? { scenario: definition.id } : {}),
          status: definition ? "blocked" : "unsupported", reason: definition ? "not-run" : "no-workload-adapter" };
      }),
    })),
  };
  const checkpoint = async () => {
    for (const repetition of campaign.repetitions) {
      repetition.summary = Object.fromEntries(["exercised", "blocked", "unsupported", "failed"].map((status) =>
        [status, repetition.plugins.filter((plugin) => plugin.status === status).length]));
    }
    campaign.status = campaign.repetitions.some(({ summary }) => summary.failed) ? "failed"
      : campaign.unmatchedScenarios.length || campaign.repetitions.some(({ summary }) => summary.blocked) ? "blocked" : "complete";
    await save("campaign.json", campaign);
  };
  await checkpoint();
  let halted = false;
  for (const repetition of campaign.repetitions) {
    for (const row of repetition.plugins.filter(({ scenario }) => scenario)) {
      const definition = definitions.find(({ id }) => id === row.scenario);
      if (halted) { row.reason = "campaign-admission-stopped"; continue; }
      if (!adapterAvailable(definition)) { row.reason = "configured-adapter-unavailable"; continue; }
      const missing = (definition.pairedWorkload?.dependencies ?? []).filter((id) => !inventory.plugins.some((plugin) => plugin.id === id));
      if (missing.length) { row.reason = "dependency-absent-from-inventory"; row.missingDependencies = missing; continue; }
      if (!execute) { row.reason = "execution-not-requested"; continue; }
      try { await verify(); }
      catch (error) {
        row.reason = "prepared-input-verification-failed";
        row.diagnostic = failureDiagnostic(error, "preverify");
        halted = true;
        await checkpoint();
        continue;
      }
      row.reason = "execution-in-progress";
      await checkpoint();
      let report;
      let stage = "run";
      try {
        report = await run({ definition, inventory, execute: true, hostRoot });
        stage = "receipt-write";
        const receipt = `repetition-${repetition.repetition}/${definition.id}.json`;
        // Persist producer facts before validation; rejected and partial receipts are evidence.
        await save(receipt, report);
        row.receipt = receipt;
        stage = "receipt-validation";
        const validated = validateResourceWorkloadReport(report, inventory, [definition]);
        assert.equal(validated.producerStatus, validated.status, "Receipt inventory differs");
        assert.equal(report.provenance.adapterSha256, pins.files.crabpot[`scripts/resource-workloads/${definition.adapter}.mjs`], "Receipt adapter differs");
        verifyReceiptPins(report, pins);
        stage = "postverify";
        await verify();
        row.status = validated.status;
        row.reason = validated.reason;
        // Incomplete executions may lack cleanup authority or a shared host prerequisite.
        // Stop rather than retrying unchanged inputs or admitting another host.
        halted = row.status !== "exercised";
      } catch (error) {
        row.status = "failed";
        row.reason = report === undefined ? "runner-threw-without-receipt" : "invalid-or-unpinned-workload-receipt";
        row.diagnostic = failureDiagnostic(error, stage);
        halted = true;
      }
      await checkpoint();
    }
  }
  await checkpoint();
  return campaign;
}

export function parseArgs(argv) {
  const args = { execute: false, repetitions: 3 };
  for (let index = 0; index < argv.length; index++) {
    const option = argv[index];
    if (option === "--execute") { args.execute = true; continue; }
    assert.ok(["--plugin-inventory", "--inputs", "--out", "--repetitions"].includes(option), `Unknown argument: ${option}`);
    const value = argv[++index];
    assert.ok(value && !value.startsWith("--"), `${option} requires a value`);
    args[option.slice(2)] = option === "--repetitions" ? Number(value) : value;
  }
  for (const key of ["plugin-inventory", "inputs", "out"]) assert.ok(args[key], `--${key} is required`);
  return args;
}

async function main() {
  const args = parseArgs(process.argv.slice(2));
  const inventory = JSON.parse(readFileSync(args["plugin-inventory"], "utf8"));
  const pins = JSON.parse(readFileSync(args.inputs, "utf8"));
  const manifest = await readManifest();
  const output = path.resolve(args.out);
  // Exclusive directory admission protects prior attempts, including interrupted ones.
  mkdirSync(output);
  const campaign = await runResourceCampaign({ manifest, inventory, pins, ...args }, {
    save: (name, value) => {
      const file = path.join(output, name);
      mkdirSync(path.dirname(file), { recursive: true });
      writeFileSync(`${file}.tmp`, `${JSON.stringify(value, null, 2)}\n`);
      renameSync(`${file}.tmp`, file);
    },
  });
  console.log(`resource campaign: ${campaign.status}; ${campaign.repetitions.length} repetitions; ${campaign.inventory.count} inventory plugins`);
  if (args.execute && campaign.status !== "complete") {
    console.error("[resource-campaign] FAILED (exit 1)");
    process.exitCode = 1;
  }
}

